# Nested tuple
tup_sets = ((23, 5, 9), (-2, -3, -1), (1, 2, 3, 5, 7))

# Accessing the second tuple
print("Second tuple:", tup_sets[1])

# Slicing elements from the second tuple
print("First two elements of second tuple:", tup_sets[1][:2])
print("Last element of second tuple:", tup_sets[1][-1])